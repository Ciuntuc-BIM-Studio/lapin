"""Type stubs for editors: ``__init__.pyi`` written from a catalogue, so ``lapin.architecture.add_wall(`` completes.

``python -m lapinbim stubs`` writes them beside the package from the open engine's catalogue (its own commands, a
premium edition's too); the published package carries those of the Lapin it was made with.
"""

from __future__ import annotations

from ._catalogue import Catalogue, Entry

# Builtins by aliases: a command may be called list or dict (component.list), which would hide the builtin in its class.
TYPES = {"str": "_str", "float": "_float", "int": "_int", "bool": "_bool", "list": "_list[Any]", "dict": "_dict[_str, Any]"}

HEAD = '''\
# Generated by `python -m lapinbim stubs` from the command catalogue of Lapin {version} ({product}). Do not edit:
# run it again against the open Lapin to have its commands.
from builtins import bool as _bool, dict as _dict, float as _float, int as _int, list as _list, str as _str
from typing import Any, Callable

from ._client import Batch as Batch, Deferred as Deferred, Lapin as _Lapin, LapinError as LapinError, Step as Step
from ._frame import Obj as Obj
from ._model import Element as Element, Model as _Model
from ._ui import UI as UI

__version__: str
__all__: list[str]
'''

TAIL = '''
class Model(_Model):
{plurals}

class Lapin(_Lapin):
{members}
    @property
    def model(self) -> Model: ...
    @property
    def ui(self) -> UI: ...

def connect(port: int | None = None, *, connect_timeout: float = 5.0) -> Lapin: ...
def client() -> Lapin: ...
def close() -> None: ...
def call(method: str, params: dict[str, Any] | None = None, timeout: float | None = None) -> Any: ...
def execute(command: str, args: dict[str, Any] | None = None) -> Any: ...
def query(name: str, args: dict[str, Any] | None = None) -> Any: ...
def undo() -> None: ...
def redo() -> None: ...
def save(path: str | None = None) -> Any: ...
def info() -> Obj: ...
def quantities(id: str | Element) -> Any: ...
def snapshot() -> Obj: ...
def state() -> Obj: ...
def batch(label: str | None = None) -> Batch: ...
def step(label: str | None = None) -> Step: ...
def selection() -> list[Element]: ...
def on(event: str, handler: Callable[..., Any]) -> Callable[[], None]: ...
def catalogue(refresh: bool = False) -> Any: ...
def ns(name: str) -> Any: ...
def command(name: str) -> Any: ...

model: Model
ui: UI
{modules}
'''


def _class_name(ns: str) -> str:
    return "_" + "".join(p[:1].upper() + p[1:] for p in ns.split("_") if p) + "Calls"


def _doc(e: Entry) -> str:
    return e.doc().replace("\\", "\\\\").replace('"""', "'''")


def _method(name: str, e: Entry) -> str:
    params = ["self", "_raw: _dict[_str, Any] | None = None", "/"]
    if e.py:
        params.append("*")
        for py, key in e.py.items():
            params.append(f"{py}: {TYPES.get(e.args[key] or '', 'Any')} | None = None")
    params.append("**_extra: Any")
    returns = "Any"
    return f'    def {name}({", ".join(params)}) -> {returns}:\n        """{_doc(e)}"""\n'


def generate(cat: Catalogue) -> str:
    """The text of ``__init__.pyi`` for this catalogue."""
    out = [HEAD.format(version=cat.version or "?", product=cat.data.get("product") or "?")]
    for ns in sorted(cat.namespaces):
        calls = cat.namespaces[ns]
        out.append(f"\nclass {_class_name(ns)}:\n")
        for name in sorted(calls):
            out.append(_method(name, calls[name]))
    plurals = "\n".join(
        f"    @property\n    def {p}(self) -> list[Element]:\n        \"\"\"{cat.classes[c].get('label') or c} ({c}).\"\"\"" for p, c in sorted(cat.plurals.items())
    ) or "    ..."
    members = "\n".join(f"    {ns}: {_class_name(ns)}" for ns in sorted(cat.namespaces))
    modules = "\n".join(f"{ns}: {_class_name(ns)}" for ns in sorted(cat.namespaces))
    out.append(TAIL.format(plurals=plurals, members=members, modules=modules))
    return "".join(out)

