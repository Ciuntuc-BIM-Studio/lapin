#!/usr/bin/env node
/**
 * The words an MEP legend writes on a drawing (its heading, the roles' and services' names, a pair's supply and return lines), in
 * every language of the interface, taken from the interface's own translations (ui/src/i18n) so the drawing and the interface name
 * a role alike: engine/src/Modules/Mep/Lapin.Mep/MepWords.json, which the MEP module embeds (MepLegend). The English words are
 * read from the engine's source (Roles.cs, Systems.cs) and the few fixed below; a word a language lacks stays English there.
 *
 *   node --experimental-strip-types scripts/mep-words.mjs           write the file
 *   node --experimental-strip-types scripts/mep-words.mjs --check   fail when the file is not what the sources make
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const mep = join(root, 'engine/src/Modules/Mep/Lapin.Mep');
const out = join(mep, 'MepWords.json');
const LANGS = ['ro', 'es', 'de', 'fr', 'da', 'it', 'pl', 'pt', 'lo', 'zh'];

const roles = [...readFileSync(join(mep, 'Roles.cs'), 'utf8').matchAll(/new\("(\w+)", "([^"]+)", "Ifc/g)].map((m) => m[2]);
const servicesSrc = readFileSync(join(mep, 'Systems.cs'), 'utf8');
const labelFn = servicesSrc.slice(servicesSrc.indexOf('public static string Label(string service)'), servicesSrc.indexOf('_ => service'));
const services = [...labelFn.matchAll(/=> "([^"]+)"/g)].map((m) => m[1]);
const fixed = ['MEP LEGEND', 'Rise (going up)', 'Drop (going down)', 'Supply line', 'Return line'];
const words = [...new Set([...fixed, ...services, ...roles])];

const table = {};
for (const lang of LANGS) {
  const mod = await import(pathToFileURL(join(root, `ui/src/i18n/${lang}.ts`)).href);
  const dict = mod[lang.toUpperCase()];
  for (const w of words) if (dict[w]) (table[w] ??= {})[lang] = dict[w];
}
const text = JSON.stringify({ about: 'Generated by scripts/mep-words.mjs from ui/src/i18n: do not edit by hand.', words: table }, null, 2) + '\n';
if (process.argv.includes('--check')) {
  let now = '';
  try { now = readFileSync(out, 'utf8'); } catch { /* none yet */ }
  if (now !== text) { console.error('MepWords.json is not what the sources make: run node --experimental-strip-types scripts/mep-words.mjs'); process.exit(1); }
  console.log('MepWords.json is up to date.');
} else {
  writeFileSync(out, text);
  const missing = words.filter((w) => LANGS.some((l) => !table[w]?.[l]));
  console.log(`MEP words: ${words.length} → ${out}${missing.length ? `; not in every language: ${missing.join(', ')}` : ''}`);
}
