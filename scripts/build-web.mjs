#!/usr/bin/env node
// Builds one product for the browser (docs/plan-browser-engine.md): the
// desktop's engine compiled to WebAssembly (AOT, trimmed, manifold linked in)
// and run in a Web Worker, with the interface built to talk to it. One
// static folder, build/<id>/web, to serve as it is. The desktop build never
// calls this, and this never touches what the desktop build makes.
//
//   node scripts/build-web.mjs [id]        (default: lapin)
//   --engine-only                           the engine alone (build/<id>/web-engine)
//
// Needs the .NET wasm-tools workload: DOTNET_ROOT, else ~/.dotnet-wasm
// (engine/src/Host/Lapin.Browser/README.md says how to install it).
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { brotliCompressSync, constants } from 'node:zlib';
import { readFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { engineModules, resolveProduct } from './product.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const id = args.find((a) => !a.startsWith('--')) ?? 'lapin';
const engineOnly = args.includes('--engine-only');
// The interface alone, over the engine built last time (build/<id>/web-engine).
const uiOnly = args.includes('--ui-only');
const product = resolveProduct(root, id);
const host = join(root, 'engine/src/Host/Lapin.Browser');
const out = join(root, 'build', id);
const sh = (cmd, a, opts = {}) => execFileSync(cmd, a, { cwd: root, stdio: 'inherit', ...opts, env: { ...process.env, ...(opts.env ?? {}) } });

// The .NET with the workload.
const home = process.env.HOME ?? process.env.USERPROFILE ?? '';
const dotnetRoot = [process.env.DOTNET_ROOT, join(home, '.dotnet-wasm')].find((d) => d && existsSync(join(d, 'packs', 'Microsoft.NET.Runtime.WebAssembly.Sdk')));
if (!dotnetRoot) { console.error('build-web: no .NET with the wasm-tools workload (see engine/src/Host/Lapin.Browser/README.md).'); process.exit(1); }
const dotnet = join(dotnetRoot, process.platform === 'win32' ? 'dotnet.exe' : 'dotnet');

// 1. manifold for the browser comes with the Lapin.Booleans package, or from the core checked out beside the repo (the engine's build says how to build it there).

// 2. The product's modules, built in (the browser loads nothing from a folder).
const modules = engineModules(root, id);
const gen = join(host, 'generated');
mkdirSync(gen, { recursive: true });
writeFileSync(join(gen, 'Product.g.props'), `<Project>
  <!-- Generated by scripts/build-web.mjs for "${id}": its engine modules. -->
  <ItemGroup>
${modules.map((m) => `    <ProjectReference Include="${relative(host, m.project).split('\\').join('/')}" />`).join('\n')}
  </ItemGroup>
</Project>
`);
writeFileSync(join(gen, 'Product.g.cs'), `// Generated by scripts/build-web.mjs for "${id}".
namespace Lapin.Browser;

static class Product
{
    public static readonly Lapin.Platform.ProductManifest Manifest = new(${JSON.stringify(product.id)}, ${JSON.stringify(product.name)}, [${product.modules.map((m) => JSON.stringify(m)).join(', ')}], null, ${product.storeys ? `[${product.storeys.map((x) => `new(${JSON.stringify(x.name)}, ${Number(x.elevation)}, ${Number(x.height)})`).join(', ')}]` : 'null'}, ${product.disciplines ? `[${product.disciplines.map((d) => JSON.stringify(d)).join(', ')}]` : 'null'});

    public static Lapin.Platform.ILapinModule[] Modules() => [${modules.map((m) => `new ${m.cls}()`).join(', ')}];
}
`);

// 2b. The lazy parts (docs/plan-browser-engine.md, Lazy parts): assemblies left out of the first download, fetched by the
// worker the first time the engine touches them, and run by the interpreter (not AOT-compiled, so their code is not in
// dotnet.native.wasm either). Only what an ordinary session never needs: a project opened, drawn in, saved, drawn on sheets.
const LAZY = [
  'Lapin.PointClouds',              // point clouds: LAS, LAZ, E57, PLY, XYZ readers and the octree (File → Link point cloud…)
  'Lapin.Mesh',                     // the 3D exchange: glTF, USD, COLLADA, OBJ writers; Fragments, BIM Open Schema, mesh imports
  'Lapin.Furniture.Models',         // the furniture models' CC0 meshes (decision 477), read with Lapin.Mesh's glTF reader when a piece of one is built
  'System.Private.Xml',             // XML: BCF, XLSX read, LandXML, MS Project, E57's header, COLLADA
  'System.Private.Xml.Linq',
  'System.Net.Http',                // reached only through System.Private.Xml's resolver
  'System.Text.Encoding.CodePages', // DXF's ANSI code pages (import and export)
];
// 2c. Modules left to the interpreter (docs/plan-browser-engine.md, Lazy parts, "The next lever", taken on 14.11.2026):
// loaded at start, since they register there and a project may hold their elements, but out of AOT, so their code is
// not in dotnet.native.wasm (their IL comes instead, much smaller). Those an ordinary session of drawing and
// documenting a building uses little; walls, floors, roofs, drawings, IFC, Studio, the structural analysis and furniture stay compiled.
const INTERPRETED = [
  'Lapin.Planning', 'Lapin.Cost', 'Lapin.Clash', 'Lapin.SiteWorks', 'Lapin.Rebar', 'Lapin.Wood', 'Lapin.Steel',
  'Lapin.Mep', 'Lapin.Civil', 'Lapin.Transport', 'Lapin.Graphs',
];
writeFileSync(join(gen, 'Parts.g.props'), `<Project>
  <!-- Generated by scripts/build-web.mjs: the lazy parts, out of the first download and out of AOT; modules out of AOT. -->
  <ItemGroup>
${LAZY.map((a) => `    <BlazorWebAssemblyLazyLoad Include="${a}.wasm" />\n    <_AOT_InternalForceInterpretAssemblies Include="${a}.dll" />`).join('\n')}
${INTERPRETED.map((a) => `    <_AOT_InternalForceInterpretAssemblies Include="${a}.dll" />`).join('\n')}
  </ItemGroup>
</Project>
`);

// 3. The engine: AOT, trimmed, with the desktop's version (0.1.<commit count>, or LAPIN_VERSION) for Help and About.
const commits = execFileSync('git', ['rev-list', '--count', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
const version = process.env.LAPIN_VERSION ?? `0.1.${commits}`;
const engineOut = join(out, 'web-engine');
if (!uiOnly) {
  rmSync(engineOut, { recursive: true, force: true });
  sh(dotnet, ['publish', host, '-c', 'Release', '-o', engineOut, '-nologo', '-v', 'q', `-p:LapinProDir=${root}/`, `-p:InformationalVersion=${version}`], { env: { DOTNET_ROOT: dotnetRoot } });
} else if (!existsSync(join(engineOut, 'wwwroot'))) { console.error(`build-web: no engine built for ${id} yet (run without --ui-only once).`); process.exit(1); }

/** A file's bytes as a browser downloads them (brotli). */
const brotli = (p) => brotliCompressSync(readFileSync(p), { params: { [constants.BROTLI_PARAM_QUALITY]: 9 } }).length;
/** Every file of a folder, but the compressed copies and the symbols. */
const filesOf = (dir) => { const o = []; const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (!/\.(br|gz|pdb)$/.test(f)) o.push(p); } }; walk(dir); return o; };
const isLazyPart = (f) => LAZY.some((a) => new RegExp(`^${a.replace(/\./g, '\\.')}\\.[a-z0-9]+\\.wasm$`).test(f));
/**
 * The download, MB brotli: `first` what the first load fetches, `all` with every lazy part. Of the interface's
 * languages (lang-*.js) only the largest counts, in both: one is loaded, when it is not English. The interface's first
 * load is its entry, the chunks it imports statically, the engine's worker and the styles; the other chunks are
 * fetched when a dialog or a view first opens.
 */
const downloadMB = (dir, first) => {
  let n = 0, lang = 0, all = 0;
  for (const p of filesOf(dir)) {
    const f = p.split(/[\\/]/).pop();
    const b = brotli(p);
    if (/^lang-.*\.js$/.test(f)) { lang = Math.max(lang, b); continue; }
    all += b;
    if (!isLazyPart(f) && (!first || first(p))) n += b;
  }
  return { first: (n + lang) / 1048576, all: (all + lang) / 1048576 };
};
const engineMB = downloadMB(join(engineOut, 'wwwroot'));
console.log(`▸ engine for ${id}: ${engineMB.first.toFixed(1)} MB at the first load, ${engineMB.all.toFixed(1)} MB with its lazy parts (brotli)`);
if (engineOnly) process.exit(0);

// 4. The interface, talking to the engine in a worker, with this product's modules.
const web = join(out, 'web');
rmSync(web, { recursive: true, force: true });
const manifest = join(out, 'product.json');
mkdirSync(out, { recursive: true });
writeFileSync(manifest, JSON.stringify(product, null, 2));
sh('pnpm', ['--filter', 'ui', 'build'], { env: { LAPIN_PRODUCT_FILE: manifest, LAPIN_UI_OUT: web, VITE_ENGINE: 'worker', LAPIN_UI_BASE: './' } });
cpSync(join(engineOut, 'wwwroot'), join(web, 'engine'), { recursive: true });
// The interface's first load: the page's entry and what it imports statically, the engine's worker, the styles.
const assets = join(web, 'assets');
const entry = /src="\.\/assets\/([^"]+\.js)"/.exec(readFileSync(join(web, 'index.html'), 'utf8'))?.[1];
const firstUi = new Set();
const follow = (f) => { if (!f || firstUi.has(f) || !existsSync(join(assets, f))) return; firstUi.add(f); for (const m of readFileSync(join(assets, f), 'utf8').matchAll(/(?:^|[;}\s])import\s*(?:[\w${},*\s]+from\s*)?["']\.\/([^"']+\.js)["']/g)) follow(m[1]); };
follow(entry);
for (const f of readdirSync(assets)) if (/^engine\.worker-.*\.js$/.test(f)) follow(f);
const first = (p) => !p.startsWith(assets) || firstUi.has(p.slice(assets.length + 1)) || p.endsWith('.css');
const total = downloadMB(web, first);
console.log(`▸ ${product.name} for the browser → build/${id}/web: ${total.first.toFixed(1)} MB at the first load, ${total.all.toFixed(1)} MB with every lazy part (brotli)`);

// 5. The budgets (docs/plan-browser-engine.md, stage 3 and Lazy parts): the first load, and everything a session may fetch.
const BUDGET_MB = 15;
const BUDGET_ALL_MB = 17;
if (total.first > BUDGET_MB) { console.error(`build-web: the first load, ${total.first.toFixed(1)} MB, is over the ${BUDGET_MB} MB budget.`); process.exit(1); }
if (total.all > BUDGET_ALL_MB) { console.error(`build-web: ${total.all.toFixed(1)} MB with the lazy parts is over the ${BUDGET_ALL_MB} MB budget.`); process.exit(1); }
