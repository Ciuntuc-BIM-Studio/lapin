#!/usr/bin/env node
// Builds one product for the browser (docs/plan-browser-engine.md): the
// desktop's engine compiled to WebAssembly (AOT, trimmed, manifold linked in)
// and run in a Web Worker, with the interface built to talk to it. One
// static folder, build/<id>/web, to serve as it is. The desktop build never
// calls this, and this never touches what the desktop build makes.
//
//   node scripts/build-web.mjs [id]        (default: lapin)
//   --engine-only                           the engine alone (build/<id>/web-engine)
//
// Needs the .NET wasm-tools workload: DOTNET_ROOT, else ~/.dotnet-wasm
// (engine/src/Host/Lapin.Browser/README.md says how to install it).
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { brotliCompressSync, constants } from 'node:zlib';
import { readFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { engineModules, resolveProduct } from './product.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const id = args.find((a) => !a.startsWith('--')) ?? 'lapin';
const engineOnly = args.includes('--engine-only');
const product = resolveProduct(root, id);
const host = join(root, 'engine/src/Host/Lapin.Browser');
const out = join(root, 'build', id);
const sh = (cmd, a, opts = {}) => execFileSync(cmd, a, { cwd: root, stdio: 'inherit', ...opts, env: { ...process.env, ...(opts.env ?? {}) } });

// The .NET with the workload.
const home = process.env.HOME ?? process.env.USERPROFILE ?? '';
const dotnetRoot = [process.env.DOTNET_ROOT, join(home, '.dotnet-wasm')].find((d) => d && existsSync(join(d, 'packs', 'Microsoft.NET.Runtime.WebAssembly.Sdk')));
if (!dotnetRoot) { console.error('build-web: no .NET with the wasm-tools workload (see engine/src/Host/Lapin.Browser/README.md).'); process.exit(1); }
const dotnet = join(dotnetRoot, process.platform === 'win32' ? 'dotnet.exe' : 'dotnet');

// 1. manifold for the browser.
if (!existsSync(join(root, 'engine/native/browser-wasm/manifoldc.a'))) sh('node', ['scripts/build-manifold.mjs', '--browser-wasm'], { env: { DOTNET_ROOT: dotnetRoot } });

// 2. The product's modules, built in (the browser loads nothing from a folder).
const modules = engineModules(root, id);
const gen = join(host, 'generated');
mkdirSync(gen, { recursive: true });
writeFileSync(join(gen, 'Product.g.props'), `<Project>
  <!-- Generated by scripts/build-web.mjs for "${id}": its engine modules. -->
  <ItemGroup>
${modules.map((m) => `    <ProjectReference Include="${relative(host, m.project).split('\\').join('/')}" />`).join('\n')}
  </ItemGroup>
</Project>
`);
writeFileSync(join(gen, 'Product.g.cs'), `// Generated by scripts/build-web.mjs for "${id}".
namespace Lapin.Browser;

static class Product
{
    public static readonly Lapin.Platform.ProductManifest Manifest = new(${JSON.stringify(product.id)}, ${JSON.stringify(product.name)}, [${product.modules.map((m) => JSON.stringify(m)).join(', ')}]);

    public static Lapin.Platform.ILapinModule[] Modules() => [${modules.map((m) => `new ${m.cls}()`).join(', ')}];
}
`);

// 3. The engine: AOT, trimmed.
const engineOut = join(out, 'web-engine');
rmSync(engineOut, { recursive: true, force: true });
sh(dotnet, ['publish', host, '-c', 'Release', '-o', engineOut, '-nologo', '-v', 'q'], { env: { DOTNET_ROOT: dotnetRoot } });

/** The bytes a browser downloads for a folder (brotli), MB. */
const brotliMB = (dir) => {
  let n = 0;
  const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (!/\.(br|gz|pdb)$/.test(f)) n += brotliCompressSync(readFileSync(p), { params: { [constants.BROTLI_PARAM_QUALITY]: 9 } }).length; } };
  walk(dir);
  return n / 1048576;
};
const engineMB = brotliMB(join(engineOut, 'wwwroot'));
console.log(`▸ engine for ${id}: ${engineMB.toFixed(1)} MB (brotli)`);
if (engineOnly) process.exit(0);

// 4. The interface, talking to the engine in a worker, with this product's modules.
const web = join(out, 'web');
rmSync(web, { recursive: true, force: true });
const manifest = join(out, 'product.json');
mkdirSync(out, { recursive: true });
writeFileSync(manifest, JSON.stringify(product, null, 2));
sh('pnpm', ['--filter', 'ui', 'build'], { env: { LAPIN_PRODUCT_FILE: manifest, LAPIN_UI_OUT: web, VITE_ENGINE: 'worker', LAPIN_UI_BASE: './' } });
cpSync(join(engineOut, 'wwwroot'), join(web, 'engine'), { recursive: true });
const totalMB = brotliMB(web);
console.log(`▸ ${product.name} for the browser → build/${id}/web (${totalMB.toFixed(1)} MB brotli)`);

// 5. The budget (docs/plan-browser-engine.md, stage 3).
const BUDGET_MB = 15;
if (totalMB > BUDGET_MB) { console.error(`build-web: ${totalMB.toFixed(1)} MB is over the ${BUDGET_MB} MB budget.`); process.exit(1); }
